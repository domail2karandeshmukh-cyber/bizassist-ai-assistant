function generateQuotation() {
  const request = document.getElementById("clientRequest").value.trim();
  const output = document.getElementById("quotationOutput");

  if (!request) {
    output.innerText = "Please enter a client request first.";
    return;
  }

  const quotation = `
BizAssist AI Solutions
Draft Quotation

Client Request Summary:
${request}

Proposed Services:
1. Requirement analysis and confirmation
2. Product/service preparation based on client needs
3. Setup and configuration support
4. One-year remote support service

Estimated Quotation:
- Product/Service Package: €7,500
- Setup and Configuration: €1,200
- Remote Support for 1 Year: €2,000

Total Estimated Amount: €10,700

Delivery Timeline:
The estimated delivery time is 10 working days after confirmation.

Terms:
- This is a draft quotation generated by BizAssist AI Assistant.
- Final pricing must be reviewed and approved by a human before sending to the client.
- Taxes and additional service charges may apply.

Email Draft:
Dear Client,

Thank you for your request. Please find below our draft quotation based on your requirements. We will be happy to discuss and adjust the offer based on your final needs.

Best regards,
BizAssist AI Solutions
`;

  output.innerText = quotation;
}

function copyQuotation() {
  const text = document.getElementById("quotationOutput").innerText;

  navigator.clipboard.writeText(text).then(() => {
    alert("Quotation copied successfully!");
  });
}
